import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

interface UnicodeInput {
  file: string;
  url: string;
  sha256: string;
  table: string;
  properties: readonly string[];
}

const inputs: readonly UnicodeInput[] = [
  {
    file: "EastAsianWidth.txt",
    url: "https://www.unicode.org/Public/17.0.0/ucd/EastAsianWidth.txt",
    sha256: "ea7ce50f3444a050333448dffef1cadd9325af55cbb764b4a2280faf52170a33",
    table: "wide",
    properties: ["W", "F"],
  },
  {
    file: "emoji-data.txt",
    url: "https://www.unicode.org/Public/17.0.0/ucd/emoji/emoji-data.txt",
    sha256: "2cb2bb9455cda83e8481541ecf5b6dfda66a3bb89efa3fa7c5297eccf607b72b",
    table: "emojiPresentation",
    properties: ["Emoji_Presentation"],
  },
];
const rangePattern = /^([\dA-F]+)(?:\.\.([\dA-F]+))?\s*;\s*(\w+)/;

/**
 * Reads a local or official Unicode input and verifies its pinned checksum.
 */
async function loadInput(input: UnicodeInput, localDirectory?: string): Promise<string> {
  let data: Buffer;

  if (localDirectory) {
    data = await readFile(resolve(localDirectory, input.file));
  } else {
    const response = await fetch(input.url);
    data = Buffer.from(await response.arrayBuffer());
  }

  const hash = createHash("sha256").update(data).digest("hex");
  if (hash !== input.sha256) {
    throw new Error(`Unicode input checksum mismatch: ${input.file}`);
  }

  return data.toString("utf8");
}

/**
 * Selects the requested properties and merges adjacent inclusive Unicode ranges.
 */
function parseRanges(text: string, properties: readonly string[]): [number, number][] {
  const ranges: [number, number][] = [];

  for (const line of text.split("\n")) {
    const match = line.match(rangePattern);
    if (!match || !properties.includes(match[3]!)) {
      continue;
    }

    const start = Number.parseInt(match[1]!, 16);
    const end = Number.parseInt(match[2] ?? match[1]!, 16);
    const previous = ranges.at(-1);

    if (previous && start === previous[1] + 1) {
      previous[1] = end;
    } else {
      ranges.push([start, end]);
    }
  }

  return ranges;
}

/**
 * Formats a flattened range table with twelve hexadecimal values per line.
 */
function formatTable(name: string, ranges: readonly [number, number][]): string {
  const values = ranges.flat().map((value) => `0x${value.toString(16)}`);
  const rows: string[] = [];

  for (let index = 0; index < values.length; index += 12) {
    const row = values.slice(index, index + 12).join(", ");
    rows.push(`  ${row},`);
  }

  return `export const ${name}: readonly number[] = [
${rows.join("\n")}
];
`;
}

/**
 * Builds the checked-in tables and their provenance only after all inputs verify.
 */
async function generateUnicode(localDirectory?: string): Promise<void> {
  const tables: string[] = [];

  for (const input of inputs) {
    const text = await loadInput(input, localDirectory);
    const ranges = parseRanges(text, input.properties);
    tables.push(formatTable(input.table, ranges));
  }

  const notices = inputs
    .map(
      (input) => `// ${input.url}
// SHA-256: ${input.sha256}`,
    )
    .join("\n");
  const output = `// Generated by scripts/generate-unicode.ts. Unicode 17.0.0. Do not edit.
// Unicode data © Unicode, Inc. See notices/UNICODE-LICENSE.txt.
${notices}
${tables.join("\n")}`;

  await writeFile(new URL("../src/unicode-width.ts", import.meta.url), output);
}

await generateUnicode(process.argv[2]);
