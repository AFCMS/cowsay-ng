import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { posix } from "node:path";

const repository = "cowsay-org/cowsay";
const destination = new URL("../src/cows/", import.meta.url);
const noticeFiles = [
  "LICENSE.txt",
  "LICENSE-COWSAY.txt",
  "LICENSE-Artistic-1.0.txt",
  "LICENSE-GPL-1.0.txt",
  "LICENSE-GPL-3.0.txt",
  "CONTRIBUTORS.md",
  "copyright",
];

interface TreeEntry {
  path: string;
  type: string;
  sha: string;
}

async function request(url: string): Promise<Response> {
  const response = await fetch(url, {
    headers: { "User-Agent": "cowsay-ng" },
    signal: AbortSignal.timeout(30_000),
  });
  if (!response.ok) {
    throw new Error(`Failed to download ${url}: HTTP ${response.status}`);
  }
  return response;
}

async function main() {
  // Resolve the ref once so the artwork and notices come from the same snapshot.
  const ref = process.argv[2] ?? "main";
  const api = `https://api.github.com/repos/${repository}`;
  const commit = (await (await request(`${api}/commits/${encodeURIComponent(ref)}`)).json()) as {
    sha: string;
  };
  const tree = (await (await request(`${api}/git/trees/${commit.sha}?recursive=1`)).json()) as {
    truncated: boolean;
    tree: TreeEntry[];
  };
  if (tree.truncated) {
    throw new Error("GitHub returned an incomplete tree; no files were written.");
  }

  const cows = tree.tree
    .filter((entry) => entry.type === "blob" && entry.path.endsWith(".cow"))
    .sort((a, b) => a.path.localeCompare(b.path));
  if (cows.length === 0) {
    throw new Error(`No .cow files found at ${ref}; no files were written.`);
  }
  const notices = noticeFiles.map((path) => {
    const entry = tree.tree.find((file) => file.type === "blob" && file.path === path);
    if (!entry) {
      throw new Error(`Missing upstream notice ${path}; no files were written.`);
    }
    return entry;
  });
  const entries = [...cows, ...notices];
  const names = entries.map((entry) => posix.basename(entry.path));
  if (new Set(names).size !== names.length) {
    throw new Error("Upstream filenames collide; no files were written.");
  }

  const exportNames = cows.map((entry) => {
    const name = posix
      .basename(entry.path, ".cow")
      .replace(/[-.]([a-z])/g, (_, letter: string) => letter.toUpperCase());
    return name === "default" ? "defaultCow" : name;
  });
  if (
    exportNames.some((name) => !/^[a-zA-Z_$][\w$]*$/.test(name)) ||
    new Set(exportNames).size !== exportNames.length
  ) {
    throw new Error(
      "Upstream filenames cannot form unique TypeScript exports; no files were written.",
    );
  }
  const cowExports = [
    "// SPDX-FileCopyrightText: 2026 AFCMS <afcm.contact@gmail.com>",
    "// SPDX-License-Identifier: MIT",
    "",
    "// Generated by scripts/download-cows.ts. Do not edit manually.",
    "/* oxlint-disable oxc/no-barrel-file -- Generated exports for cow text assets. */",
    "",
    ...cows.map(
      (entry, index) =>
        `export { default as ${exportNames[index]} } from ${JSON.stringify(`./cows/${posix.basename(entry.path)}`)} with { type: "text" };`,
    ),
    "",
  ].join("\n");

  // Finish and verify every download before changing the local collection.
  const downloads: { name: string; contents: Buffer }[] = [];
  for (let offset = 0; offset < entries.length; offset += 8) {
    const batch = await Promise.all(
      entries.slice(offset, offset + 8).map(async (entry) => {
        const path = entry.path.split("/").map(encodeURIComponent).join("/");
        const response = await request(
          `https://raw.githubusercontent.com/${repository}/${commit.sha}/${path}`,
        );
        const contents = Buffer.from(await response.arrayBuffer());
        const hash = createHash("sha1")
          .update(`blob ${contents.length}\0`)
          .update(contents)
          .digest("hex");
        if (hash !== entry.sha) {
          throw new Error(`Integrity check failed for ${entry.path}; no files were written.`);
        }
        return { name: posix.basename(entry.path), contents };
      }),
    );
    downloads.push(...batch);
  }

  const source = `https://github.com/${repository}/tree/${commit.sha}`;
  const attribution = `# Cow artwork attribution

These ${cows.length} beautiful cow files are copied verbatim from
[cowsay-org/cowsay](${source}) at commit \`${commit.sha}\`.
All author comments and artwork in the original files are preserved.

Thank you to Tony Monroe, the original author of Cowsay; Andrew Janke, who
maintains the cowsay-org fork; and all the artists and contributors who created
these cows. See the upstream [contributors](./CONTRIBUTORS.md), the per-file
[copyright notices](./copyright), and the comments in each cow for individual credits.

The cow files retain their upstream licenses and are not covered by cowsay-ng's
MIT license. See the upstream [license statement](./LICENSE.txt),
[original Cowsay terms](./LICENSE-COWSAY.txt), [Artistic License 1.0](./LICENSE-Artistic-1.0.txt),
[GNU GPL 1.0](./LICENSE-GPL-1.0.txt), and [GNU GPL 3.0](./LICENSE-GPL-3.0.txt).
Upstream describes the collection as GPL 3 or later, with broader licensing for
many files; its per-file copyright notices identify sus.cow as GPL-3.0-only.
See also the upstream [licensing notes](${source}/doc-project/Licensing.md).

To refresh the cows and these notices, run \`pnpm cows:download\` from the project
root. Pass a commit, tag, or branch as an argument to select a specific revision:
\`pnpm cows:download ${commit.sha}\`.
`;

  await mkdir(destination, { recursive: true });
  for (const { name, contents } of downloads) {
    await writeFile(new URL(name, destination), contents);
  }
  await writeFile(new URL("ATTRIBUTION.md", destination), attribution);
  await writeFile(new URL("../cows.ts", destination), cowExports);
  console.log(
    `Downloaded ${cows.length} cows and their notices from ${repository}@${commit.sha}, and generated src/cows.ts.`,
  );
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
